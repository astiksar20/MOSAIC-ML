// Builds MOSAIC-ML_Evidence.docx: screenshots, graphs and captured outputs.
// Every picture is a real screenshot or a figure generated from executed code.
// Run from the repository root: node scripts/make_evidence_doc.js
const fs = require('fs');
const path = require('path');
const {
  Document, Packer, Paragraph, TextRun, ImageRun, HeadingLevel, AlignmentType,
  Table, TableRow, TableCell, WidthType, BorderStyle, ShadingType, PageBreak,
} = require('docx');

const R = path.resolve(__dirname, '..');
const DIMS = JSON.parse(fs.readFileSync(path.join(R, 'reports/evidence/image_sizes.json')));
const EV = JSON.parse(fs.readFileSync(path.join(R, 'reports/results/model_evaluation.json')));
const txt = (f) => fs.readFileSync(path.join(R, 'reports/evidence/text', f), 'utf8');
const FONT = 'Calibri';
const MAXW = 620; // px at 96 dpi = 6.46 in

const H1 = (t) => new Paragraph({ heading: HeadingLevel.HEADING_1, spacing: { before: 240, after: 120 }, children: [new TextRun({ text: t, font: FONT, bold: true, size: 32 })] });
const H2 = (t) => new Paragraph({ heading: HeadingLevel.HEADING_2, spacing: { before: 200, after: 80 }, children: [new TextRun({ text: t, font: FONT, bold: true, size: 26 })] });
const p = (t, o = {}) => new Paragraph({ spacing: { after: 100 }, children: [new TextRun({ text: t, font: FONT, size: 22, italics: o.i, bold: o.b })] });
const cap = (t) => new Paragraph({ spacing: { before: 60, after: 240 }, alignment: AlignmentType.CENTER, children: [new TextRun({ text: t, font: FONT, size: 19, italics: true, color: '444444' })] });
const pre = (t) => t.replace(/\r/g, '').split('\n').map((line) => new Paragraph({
  spacing: { after: 0, line: 220 }, shading: { type: ShadingType.CLEAR, fill: 'F3F3F3' },
  children: [new TextRun({ text: line || ' ', font: 'Consolas', size: 16 })],
}));
let figN = 0;
const img = (rel, caption, maxw = MAXW) => {
  const [w, h] = DIMS[rel];
  const W = Math.min(maxw, w), H = Math.round(h * W / w);
  figN += 1;
  return [
    new Paragraph({ alignment: AlignmentType.CENTER, keepNext: true, spacing: { before: 120 },
      children: [new ImageRun({ type: 'png', data: fs.readFileSync(path.join(R, rel)), transformation: { width: W, height: H } })] }),
    cap(`Evidence ${figN}. ${caption}`),
  ];
};
const cell = (t, o = {}) => new TableCell({
  width: { size: o.w, type: WidthType.DXA },
  shading: o.head ? { type: ShadingType.CLEAR, fill: 'E3E3E3' } : (o.hl ? { type: ShadingType.CLEAR, fill: 'FFF1E6' } : undefined),
  margins: { top: 40, bottom: 40, left: 80, right: 80 },
  children: [new Paragraph({ alignment: o.left ? AlignmentType.LEFT : AlignmentType.CENTER,
    children: [new TextRun({ text: t, font: FONT, size: 18, bold: o.head || o.hl })] })],
});
const table = (widths, rows, hlRow = -1) => new Table({
  columnWidths: widths, width: { size: widths.reduce((a, b) => a + b), type: WidthType.DXA },
  borders: { top: { style: BorderStyle.SINGLE, size: 4 }, bottom: { style: BorderStyle.SINGLE, size: 4 },
    left: { style: BorderStyle.SINGLE, size: 4 }, right: { style: BorderStyle.SINGLE, size: 4 },
    insideHorizontal: { style: BorderStyle.SINGLE, size: 2, color: 'AAAAAA' }, insideVertical: { style: BorderStyle.SINGLE, size: 2, color: 'AAAAAA' } },
  rows: rows.map((r, i) => new TableRow({ children: r.map((t, j) => cell(String(t), { w: widths[j], head: i === 0, hl: i === hlRow, left: j === 0 })) })),
});
const f4 = (x) => (x == null ? '—' : Number(x).toFixed(4));
const brk = () => new Paragraph({ children: [new PageBreak()] });

const C = [];
const add = (...xs) => xs.flat().forEach((x) => C.push(x));

// ---------- cover ----------
add(new Paragraph({ alignment: AlignmentType.CENTER, spacing: { before: 1800, after: 200 }, children: [new TextRun({ text: 'MOSAIC-ML', font: FONT, bold: true, size: 56 })] }),
  new Paragraph({ alignment: AlignmentType.CENTER, spacing: { after: 200 }, children: [new TextRun({ text: 'Evidence of Implementation and Results', font: FONT, size: 36 })] }),
  new Paragraph({ alignment: AlignmentType.CENTER, spacing: { after: 600 }, children: [new TextRun({ text: 'Android Vulnerability and Intrusion Risk Analysis — Astik Sarkar', font: FONT, size: 24, color: '555555' })] }),
  p('Every picture in this document is either a screenshot of the running system or notebook, or a graph generated by the project’s own scripts from executed results. No value was typed in by hand. The numbers behind each graph are saved as CSV/JSON in reports/results/ of the project folder.'),
  p(`Environment: Python 3.10, scikit-learn ${EV.sklearn_version}, NumPy ${EV.numpy_version}, SciPy ${EV.scipy_version}. Training record generated ${EV.generated_utc}.`),
  p('Contents: 1. Model training (notebook)  ·  2. Model results  ·  3. Graphs  ·  4. Frontend dashboard  ·  5. Backend API  ·  6. Database  ·  7. Automated tests  ·  8. Not verified'),
  brk());

// ---------- 1. notebook ----------
add(H1('1. Model Training — Notebook Run'),
  p('The notebook notebooks/MOSAIC_ML_Model_Training.ipynb was executed end to end (951 seconds). It loads MH-100K, checks the matrix is not corrupted, removes duplicates, splits the data, trains all nine configurations of the three models, evaluates the selected model once on the test split, draws the graphs, and finally compares its numbers with the shipped results.'));
const NB = [
  ['01_data_loaded_and_checked', 'Dataset loaded: 101,934 apps × 24,833 features. The integrity check confirms rows are not scrambled (first rows have 1,288, 2,291, 2,700 and 41 active features).'],
  ['02_deduplication', 'Deduplication: 43,358 duplicate rows removed, 58,576 unique apps kept; malware becomes 13.10%, so an all-“benign” guess would score 0.8690 accuracy.'],
  ['03_split', 'Stratified 70/15/15 split with seed 42: train 41,003, validation 8,786, test 8,787.'],
  ['04_training_9_configs', 'All nine configurations trained and scored on the validation split, plus the count-only control.'],
  ['05_results_table_and_selection', 'Full validation results table and the selection: class-weighted Logistic Regression (balanced accuracy 0.9631).'],
  ['06_final_test_once', 'The selected model refitted on train + validation and evaluated once on the test split.'],
  ['07_fig4_model_comparison', 'Notebook graph: six metrics for the best configuration of each model and the control.'],
  ['08_fig5_confusion_matrices', 'Notebook graph: confusion matrices (validation for each model, final test for the selected one).'],
  ['09_fig6_roc_pr', 'Notebook graph: ROC and precision-recall curves.'],
  ['10_fig8_all_configs', 'Notebook graph: balanced accuracy of every configuration tried.'],
  ['11_match_with_shipped', 'Reproducibility check: every value from the notebook equals the value shipped with the project — the notebook prints MATCH.'],
];
NB.forEach(([f, t]) => add(img(`reports/notebook_proof/${f}.png`, t)));
add(brk());

// ---------- 2. results tables ----------
add(H1('2. Model Results'), H2('2.1 All nine configurations (validation split, n = 8,786)'));
const vr = EV.validation_results;
const selIdx = vr.findIndex((r) => r.config === EV.selected_config) + 1;
add(table([2700, 1100, 1100, 1100, 1100, 1100], [
  ['Configuration', 'Accuracy', 'Balanced acc.', 'Malware recall', 'Malware F1', 'False-pos. rate'],
  ...vr.map((r) => [r.config.split(/\s+/).join(' '), f4(r.accuracy), f4(r.balanced_accuracy), f4(r.malware_recall), f4(r.malware_f1), f4(r.false_positive_rate)]),
], selIdx));
add(cap('Highlighted row: the selected configuration. Source: reports/results/model_evaluation.json.'));
add(H2('2.2 Final test result (evaluated once)'));
const t = EV.test_result; const cm = t.confusion_matrix;
add(table([4600, 4600], [
  ['Metric', `${EV.selected_config.split(/\s+/).join(' ')} on test (n = 8,787)`],
  ['Accuracy', f4(t.accuracy)], ['Balanced accuracy', f4(t.balanced_accuracy)],
  ['Malware precision', f4(t.malware_precision)], ['Malware recall', f4(t.malware_recall)],
  ['Malware F1', f4(t.malware_f1)], ['False-positive rate', f4(t.false_positive_rate)],
  ['ROC-AUC', f4(t.roc_auc)], ['PR-AUC', f4(t.pr_auc)],
  ['Confusion matrix', `TN ${cm[0][0].toLocaleString()} · FP ${cm[0][1]} · FN ${cm[1][0]} · TP ${cm[1][1].toLocaleString()}`],
]));
add(cap('The test split was not used to choose anything in this run; it was evaluated once after selection.'), brk());

// ---------- 3. graphs ----------
add(H1('3. Graphs'));
const G = [
  ['fig02_class_distribution', 'Class distribution of the raw dataset (labels: vt_detection ≥ 4).'],
  ['fig03_sparsity', 'Active features per app. Malware median 42 vs benign 2,082 — the shortcut the control model exploits.'],
  ['fig04_model_comparison', 'Validation metrics, best configuration of each model, with the count-only control in red.'],
  ['fig05_confusion_matrices', 'Confusion matrices: validation for each model, and the final test result.'],
  ['fig06_roc_pr_curves', 'ROC and precision-recall curves on validation.'],
  ['fig07_threshold_analysis', 'Precision, recall, false-positive rate and balanced accuracy across decision thresholds (selected model).'],
  ['fig08_tuning_grid', 'Every configuration tried, validation balanced accuracy.'],
  ['fig09_permission_weights', 'Permission risk weights r = √(α(1−β)), fitted on the training split only.'],
  ['fig10_permission_score_eval', 'Permission risk score evaluation (ROC-AUC 0.7734, PR-AUC 0.2804 on test).'],
  ['fig11_two_analyses', 'Permission score vs ML model on the test split: correlation 0.30; precision by agreement pattern.'],
];
G.forEach(([f, c2]) => add(img(`reports/figures/${f}.png`, c2)));
add(img('reports/figures/paper/fig_p1_pipeline.png', 'System pipeline (Fig. 1 of the paper).', 380), brk());

// ---------- 4. frontend ----------
add(H1('4. Frontend Dashboard'),
  p('Screenshots of the React dashboard served by the backend at http://127.0.0.1:7860, taken from a fresh unzip of the final package. A real APK from test_apks/ was analysed.'));
const D = [
  ['d01_home', 'Home screen. The header shows API ONLINE, confirming the frontend is connected to the backend.'],
  ['d02_rejects_fake_apk', 'Input validation: a text file renamed to .apk is rejected because it has no ZIP header.'],
  ['d03_apk_selected', 'A real APK selected for analysis.'],
  ['d04_coverage', 'Step 01 — feature coverage: 97 of 24,833 features matched (5 permissions, 1 intent, 91 API calls).'],
  ['d05_ml', 'Step 02 — ML classification by the loaded model (Logistic Regression): BENIGN, malware probability 0.45%.'],
  ['d06_permission', 'Step 03 — permission risk score with the matched permissions and their weights.'],
  ['d07_cve', 'Step 04 — CVE/NVD lookup. Lookups report FAILED here because the test environment had no internet access; the failure is reported honestly instead of as “0 vulnerabilities”.'],
  ['d08_hids', 'Step 05 — HIDS prototype, clearly labelled as synthetic data.'],
  ['d09_assessment', 'Step 06 — prototype combined assessment, with its limitations listed.'],
  ['d10_history', 'Scan history read from the database.'],
];
D.forEach(([f, c2]) => add(img(`reports/evidence/screens/${f}.png`, c2)));
add(brk());

// ---------- 5. backend ----------
add(H1('5. Backend API'));
add(img('reports/evidence/screens/b01_health.png', 'GET /health in the browser: status healthy, model Logistic Regression loaded.'));
add(img('reports/evidence/screens/b03_scans.png', 'GET /scans in the browser: stored scan history from the database.'));
add(H2('5.1 /health response'), ...pre(txt('health.json')));
const scan = JSON.parse(txt('scan.json'));
const excerpt = { filename: scan.filename, apk_sha256: scan.apk_sha256, feature_coverage: scan.feature_coverage, ml_analysis: scan.ml_analysis,
  permission_risk: { score: scan.permission_risk.score, status: scan.permission_risk.status, matched: scan.permission_risk.matched_permissions ?? scan.permission_risk.permissions },
  storage: scan.storage };
add(H2('5.2 POST /analyze-apk response (excerpt)'), ...pre(JSON.stringify(excerpt, null, 2)));
add(cap('The full response (460 lines) is saved as reports/evidence/text/scan.json.'));
add(H2('5.3 Rejecting an invalid file'), ...pre(txt('reject.txt')));
add(H2('5.4 Server log for these requests'), ...pre(txt('server_log.txt')), brk());

// ---------- 6. database ----------
add(H1('6. Database'),
  p('SQLite is used by default (PostgreSQL when DATABASE_URL is set). Only a summary and the APK’s SHA-256 are stored, never the APK itself. The query below was run directly on storage/mosaic.db after the server had been stopped and restarted: the earlier scan is still there, which shows history persists across restarts.'),
  ...pre(txt('db.txt')), brk());

// ---------- 7. tests ----------
add(H1('7. Automated Tests'), p('tests_permission_risk.py, run on the unzipped final package:'), ...pre(txt('tests.txt')));
add(p('Also verified by execution: the final zip unzipped into an empty folder and run with dependencies installed from requirements.txt alone (versions 1.6.1 / 1.26.4 / 1.15.3); the dashboard, /health, a real scan and history all worked. The saved models reproduce their recorded confusion matrices exactly when reloaded.'));

// ---------- 8. not verified ----------
add(H1('8. Not Verified — Stated Honestly'),
  p('• The Docker image has not been built. Docker Hub was blocked in the build environment. Everything the image contains was assembled and run the way the container runs it, but the first docker build on a real machine is still to be done.'),
  p('• NVD/CVE lookup has never returned a record, because every test ran without internet access. The success path is untested.'),
  p('• HIDS telemetry is synthetic prototype data, labelled as such in the dashboard.'),
  p('• Results come from a single data split; there are no confidence intervals and the probabilities are not calibrated.'));

const doc = new Document({
  creator: 'Astik Sarkar', title: 'MOSAIC-ML — Evidence of Implementation and Results',
  styles: { default: { document: { run: { font: FONT, size: 22 } } } },
  sections: [{ properties: { page: { size: { width: 12240, height: 15840 }, margin: { top: 1080, bottom: 1080, left: 1080, right: 1080 } } }, children: C }],
});
const out = path.join(R, 'MOSAIC-ML_Evidence.docx');
Packer.toBuffer(doc).then((b) => { fs.writeFileSync(out, b); console.log('written', out, (b.length / 1048576).toFixed(1), 'MB,', figN, 'pictures'); });
